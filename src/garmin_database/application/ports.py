"""Contracts owned by the application; adapters supply their implementations."""

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Callable, Protocol


class ReadFailure(RuntimeError):
    """Storage failed; its private exception is never part of a public response."""

    def __init__(self, message, *, reason="database"):
        super().__init__(message)
        self.reason = reason


class ReadSnapshot(Protocol):
    catalog: list[dict]
    revision: int
    policy_revision: str | None
    identity: list

    def select(self, settings, channel, requested) -> list[dict]: ...
    def daily(
        self, parameter, start, end, stop=None, *, publish_cache=False
    ) -> list[dict]: ...
    def coverage(self, start, end) -> dict: ...
    def rows(self, parameter, start, end): ...
    def availability(self, parameter): ...


class Readings(Protocol):
    def snapshot(self, stop=None) -> AbstractContextManager[ReadSnapshot]: ...


class SettingsStore(Protocol):
    def load(self, path=None): ...
    def save(self, settings, path=None) -> None: ...
    def location(self, path=None) -> Path: ...


class ImportRepository(Protocol):
    def writer_lock(self) -> AbstractContextManager: ...
    def initialize(self) -> None: ...
    def restore_days(self, days: dict) -> None: ...
    def day(self, day: str): ...
    def local_invalid(self, day: str, error_type: str) -> None: ...
    def attempt(self, day: str) -> None: ...
    def cancel_attempt(self, day: str) -> None: ...
    def failed(self, day: str, status: int | None, error_type: str) -> None: ...


class ArchiveStore(Protocol):
    def restore_manifest(self) -> dict: ...
    def path(self, day: str) -> Path: ...
    def exists(self, day: str) -> bool: ...
    def save(self, day: str, payload: bytes) -> None: ...


class ArchiveImporter(Protocol):
    def archive(
        self,
        path,
        stop=None,
        progress=lambda *a: None,
        force=False,
        origin="local_archive",
    ) -> int: ...


class GarminSource(Protocol):
    def login(self, email=None, password=None, mfa=None, stop=None, progress=None): ...
    def download_health_snapshot(self, day: str) -> bytes: ...


class ExportSink(Protocol):
    def generate(
        self,
        output,
        parameters,
        start,
        end,
        recent_days,
        stop,
        summary_period,
        progress,
        snapshot,
    ): ...


class DesktopServices(Protocol):
    """Operations exposed to GUI/CLI; SQL connections never cross this boundary."""

    settings_store: SettingsStore
    source_factory: Callable
    session_factory: Callable

    def prepare(self, settings): ...
    def reconfigure(self, settings): ...
    def session_available(self) -> bool: ...
    def open_folder(self, path) -> None: ...
    def open_url(self, url: str) -> None: ...
    def login(self, email, password, mfa, stop, progress): ...
    def status(self) -> dict: ...
    def overview(self, stop, catalog_revision=None, include_catalog=True) -> dict: ...
    def catalog(self, stop, known_revision=None) -> dict: ...
    def parameters(self) -> list[dict]: ...
    def chart(self, parameter, start, end, stop=None): ...
    def sync(
        self,
        start,
        end,
        stop,
        progress,
        local_only=False,
        force=False,
        delay=3,
        *,
        detailed=False,
    ): ...
    def export(self, settings, settings_path): ...
